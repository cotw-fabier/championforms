#!/usr/bin/env bash
# Runs the championforms_documents editor benchmark in PROFILE mode in a real
# macOS window and prints its table plus real frame timings.
#
#   tool/profile_documents.sh            # profile (default)
#   tool/profile_documents.sh --debug    # same harness in debug, to compare
#
# The benchmark lives in
# packages/championforms_documents/test/perf/document_perf_bench.dart and
# also runs as a debug widget test:
#   (cd packages/championforms_documents && \
#    flutter test --tags perf --run-skipped test/perf/)
#
# `flutter test` has no --profile flag (so tool/macos_integration_test.sh
# can't do this); profile mode needs `flutter drive`. This script generates a
# throwaway macOS app under build/profile_documents/ (gitignored, not a
# workspace member) that depends on the workspace packages by path, copies
# the benchmark in as an integration test and drives it with
# `flutter drive --profile -d macos`. Like tool/macos_integration_test.sh it
# then closes any leftover process of that app (matched by its build/macos/
# path only) and exits with flutter's status. macOS only.
#
# Reading the output: in a live binding, the benchmark's "keystroke" row is
# wall time for typeImeText, which pumps several real frames and waits for
# vsync each time, so it is dominated by vsync waits (~7 x 16.7 ms). The
# "keystroke frames" row of the engine frame timings (build / raster per
# frame while typing) is the per-keystroke cost to look at.
set -uo pipefail

mode=--profile
case "${1:-}" in
  "") ;;
  --profile|--debug) mode=$1 ;;
  *) echo "usage: $0 [--profile|--debug]" >&2; exit 64 ;;
esac

if [[ "$(uname)" != Darwin ]]; then
  echo "$0: macOS only (flutter drive -d macos)" >&2
  exit 69
fi

repo="$(cd "$(dirname "$0")/.." && pwd)"
app="$repo/build/profile_documents/app"
bench="$repo/packages/championforms_documents/test/perf/document_perf_bench.dart"

if [[ ! -f "$app/pubspec.yaml" ]]; then
  mkdir -p "$(dirname "$app")"
  (cd "$(dirname "$app")" &&
    flutter create --platforms=macos --project-name profile_documents_app \
      --org com.championforms --empty app) || exit 1
fi

cat > "$app/pubspec.yaml" <<EOF
name: profile_documents_app
description: Generated by tool/profile_documents.sh. Do not edit.
publish_to: none
environment:
  sdk: ">=3.10.0 <4.0.0"
dependencies:
  flutter:
    sdk: flutter
  championforms: any
  championforms_documents: any
  super_editor: any
dev_dependencies:
  flutter_test:
    sdk: flutter
  integration_test:
    sdk: flutter
  flutter_driver:
    sdk: flutter
dependency_overrides:
  championforms:
    path: $repo
  championforms_clipboard:
    path: $repo/packages/championforms_clipboard
  championforms_documents:
    path: $repo/packages/championforms_documents
flutter:
  uses-material-design: true
EOF

mkdir -p "$app/integration_test" "$app/test_driver"
cp "$bench" "$app/integration_test/document_perf_bench.dart"

cat > "$app/test_driver/integration_test.dart" <<'EOF'
import 'package:integration_test/integration_test_driver.dart';

Future<void> main() => integrationDriver();
EOF

cat > "$app/integration_test/document_perf_profile_test.dart" <<'EOF'
import 'dart:developer' show Timeline;
import 'dart:ui' show FramePhase, FrameTiming;

import 'package:flutter/foundation.dart';
import 'package:flutter/scheduler.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';

import 'document_perf_bench.dart';

double _p(List<Duration> sorted, double q) => sorted.isEmpty
    ? 0
    : sorted[((sorted.length * q).ceil() - 1).clamp(0, sorted.length - 1)]
              .inMicroseconds /
          1000;

void main() {
  final binding = IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  binding.framePolicy = LiveTestWidgetsFlutterBindingFramePolicy.fullyLive;

  testWidgets('document editor benchmark', (tester) async {
    // Engine frame timings, split into the timed keystrokes and the rest.
    // Timings arrive in batches after the frames, so each frame is
    // attributed by its vsync start, which is on the Timeline clock.
    final timings = <FrameTiming>[];
    void collect(List<FrameTiming> t) => timings.addAll(t);
    SchedulerBinding.instance.addTimingsCallback(collect);
    var typingFrom = 0, typingTo = 0;
    int now() => Timeline.now;
    final mode = kProfileMode ? 'profile, AOT' : 'debug, JIT';
    final report = await runDocumentBenchmark(
      tester,
      mode: '$mode, macOS',
      onPhase: (phase) {
        if (phase == 'keystrokes') typingFrom = now();
        if (phase == 'done') typingTo = now();
      },
    );
    await tester.pumpAndSettle();
    await Future<void>.delayed(const Duration(seconds: 1));
    SchedulerBinding.instance.removeTimingsCallback(collect);

    bool typing(FrameTiming t) {
      final start = t.timestampInMicroseconds(FramePhase.vsyncStart);
      return start >= typingFrom && start <= typingTo;
    }

    String row(String label, Iterable<FrameTiming> frames) {
      final list = frames.toList();
      final build = [for (final t in list) t.buildDuration]..sort();
      final raster = [for (final t in list) t.rasterDuration]..sort();
      final total = [for (final t in list) t.totalSpan]..sort();
      String f(List<Duration> d) =>
          '${_p(d, .5).toStringAsFixed(2).padLeft(7)} '
          '${_p(d, .95).toStringAsFixed(2).padLeft(7)} '
          '${_p(d, 1).toStringAsFixed(2).padLeft(7)}';
      return '| ${label.padRight(18)} | ${list.length.toString().padLeft(4)} '
          '| ${f(build)} | ${f(raster)} | ${f(total)} |';
    }

    final lines = [
      report.table(),
      '',
      'Engine frame timings (ms: median p95 max)',
      '| frames             |    n |   build (med p95 max)   '
          '|  raster (med p95 max)   |  total span (med p95 max) |',
      row('keystroke frames', timings.where(typing)),
      row('all frames', timings),
    ];
    binding.reportData = {
      'table': lines.join('\n'),
      for (final e in report.stats.entries)
        e.key: {
          'n': e.value.samples.length,
          'medianMs': e.value.medianMs,
          'p95Ms': e.value.p95Ms,
          'maxMs': e.value.maxMs,
        },
    };
  });
}
EOF

(cd "$app" && flutter pub get >/dev/null) || exit 1

# The driver writes binding.reportData to build/integration_response_data.json.
rm -f "$app/build/integration_response_data.json"
(cd "$app" && flutter drive "$mode" -d macos \
  --driver=test_driver/integration_test.dart \
  --target=integration_test/document_perf_profile_test.dart)
status=$?

build_dir="$app/build/macos/"
sleep 1  # let a delayed relaunch appear before checking
for _ in 1 2 3 4 5; do
  pgrep -f "^$build_dir" >/dev/null || break
  sleep 1
done
if pgrep -f "^$build_dir" >/dev/null; then
  echo "Closing leftover benchmark app under $build_dir" >&2
  pkill -f "^$build_dir"
fi

response="$app/build/integration_response_data.json"
if [[ -f "$response" ]]; then
  echo
  python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["table"])' \
    "$response" 2>/dev/null || cat "$response"
fi

exit "$status"
